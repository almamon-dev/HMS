export interface BloodGroupStock {
  group: string;
  totalBags: number;
  wholeBlood: number;
  prbc: number;
  platelets: number;
  ffp: number;
  status: 'Normal' | 'Low' | 'Critical';
}

export interface BloodIssueRecord {
  id: string;
  issueNo: string;
  caseId: string;
  date: string;
  patientName: string;
  patientId: string;
  doctorName: string;
  donorName: string;
  bagNo: string;
  bloodGroup: string;
  component: 'Whole Blood' | 'PRBC' | 'Platelets' | 'FFP' | 'Cryoprecipitate';
  amount: number;
  discountAmount: number;
  discountPercent: number;
  taxAmount: number;
  taxPercent: number;
  netAmount: number;
  paidAmount: number;
  balanceAmount: number;
  crossMatchingStatus: 'Compatible' | 'Matched';
}

export interface BloodDonorRecord {
  id: string;
  donorId: string;
  donorName: string;
  gender: 'Male' | 'Female';
  age: number;
  bloodGroup: string;
  mobile: string;
  fatherName: string;
  address: string;
  lastDonationDate: string;
  totalDonations: number;
}

export interface BloodDonationBagRecord {
  id: string;
  bagNo: string;
  donorName: string;
  donorId: string;
  bloodGroup: string;
  donateDate: string;
  volumeMl: number;
  lotNo: string;
  component: string;
  expiryDate: string;
  screeningStatus: 'Non-Reactive (Safe)' | 'Verified';
}

